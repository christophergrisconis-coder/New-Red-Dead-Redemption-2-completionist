import type { LocationEntry, Region } from "./types";

/**
 * 94 discoverable locations required for the official 100% completion map
 * ("Location Discoverer") plus a small number of tracked non-required
 * landmarks. Region grouping follows the in-game map segmentation.
 */

type LocType = LocationEntry["locationType"];

interface Seed {
  slug: string;
  title: string;
  region: Region;
  type: LocType;
  summary: string;
  requiredFor100?: boolean;
}

function loc(s: Seed): LocationEntry {
  return {
    id: `loc-${s.slug}`,
    title: s.title,
    category: "locations",
    locationType: s.type,
    region: s.region,
    isRequiredForOfficial100: s.requiredFor100 ?? true,
    isOptionalSideContent: !(s.requiredFor100 ?? true),
    summary: s.summary,
    descriptiveWalkthrough: `Discovered by riding into the marked area. ${s.summary}`,
    keyObjectives: ["Enter the map area"],
    rewardsOrOutcomes: ["Fast-travel node + map completion credit"],
    checklistSteps: [{ id: "discover", label: "Discover" }],
    tags: [s.type.toLowerCase().replace(/ /g, "-")],
  };
}

