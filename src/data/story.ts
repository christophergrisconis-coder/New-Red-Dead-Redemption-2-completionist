import type { StoryMission, Region } from "./types";

/**
 * All 57 Red Dead Redemption story missions, verified against the community
 * wiki's mission list (which matches the IGN walkthrough structure of four
 * chapters — New Austin, Nuevo Paraíso, West Elizabeth, Homestead — and 57
 * total single-player missions). Walkthrough text is original.
 */

type Chapter =
  | "Chapter 1 — New Austin"
  | "Chapter 2 — Nuevo Paraíso"
  | "Chapter 3 — West Elizabeth"
  | "Chapter 4 — Homestead (Epilogue)";

interface Seed {
  slug: string;
  title: string;
  chapter: Chapter;
  giver: string;
  region: Region;
  summary: string;
  walkthrough: string;
  objectives: string[];
  outcomes?: string[];
  followUps?: string[];
  missable?: string[];
  after?: string[];
  tags?: string[];
}

function mission(s: Seed): StoryMission {
  return {
    id: `story-${s.slug}`,
    title: s.title,
    category: "story",
    chapter: s.chapter,
    missionGiver: s.giver,
    region: s.region,
    isRequiredForOfficial100: true,
    isOptionalSideContent: false,
    unlocksAfter: s.after?.map((a) => `story-${a}`),
    summary: s.summary,
    descriptiveWalkthrough: s.walkthrough,
    keyObjectives: s.objectives,
    rewardsOrOutcomes: s.outcomes ?? ["Story progress", "Chapter advancement"],
    followUpOpportunities: s.followUps,
    missableWarnings: s.missable,
    checklistSteps: [
      { id: "start", label: "Start mission" },
      { id: "objectives", label: "Complete key objectives" },
      { id: "finish", label: "Finish and bank progress" },
    ],
    tags: s.tags,
  };
}

